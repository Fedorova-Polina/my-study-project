choice = input("Куда поедешь, витязь? (прямо/направо/налево) ").strip().lower()
if choice == 'прямо':
    print("Камень гласит: Живу не бывати! Нет пути ни проезжему, ни прохожему.")
elif choice == 'направо':
    print("Камень гласит: Женату быти! Найдешь свою суженую.")
elif choice == 'налево':
    print("Камень гласит: Богату быти! Найдешь золото и славу.")
else:
    print("Стоишь ты на месте, а вороны кружат... Выбери верный путь!")